import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createState,advance,getBusinessEconomy,getInfrastructureNeeds,getPublicProgramCaps,exportState,hydrateState,spendPublicBudget} from '../web/runtime-anthem-v15/engine.js';
const NOW=1700000000000;
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-7,`${a} vs ${b}`);
const growing=()=>{const s=createState(NOW);s.worldEconomyEnabled=true;s.owned.matches=50;s.cash=10000;s.communism=500;s.publicBudget=0;return s;};
test('early activity does not incur infrastructure fees while small economies require expanded services',()=>{
 const s=createState(NOW);s.worldEconomyEnabled=true;
 assert.equal(getBusinessEconomy(s).infrastructure.costPerSecond,0);
 s.owned.matches=1;
 assert.equal(getBusinessEconomy(s).infrastructure.costPerSecond,0);
 const growingState=growing(),needs=getBusinessEconomy(growingState).infrastructure;
 assert.ok(needs.required.services>=1);
 assert.ok(needs.required.transport>=1);
 assert.ok(needs.required.housing>=1);
 assert.ok(needs.costPerSecond>0);
 assert.ok(Object.values(needs.missing).some(n=>n>0));
});
test('unfunded public minimum drains public taxes and then real commercial cash, even offline',()=>{
 const s=growing(),finances=getBusinessEconomy(s);
 assert.ok(finances.infrastructure.costPerSecond>finances.taxesCollectedPerSecond);
 const expectedCashChange=finances.netToTreasuryPerSecond-(finances.infrastructure.costPerSecond-finances.taxesCollectedPerSecond);
 const initial=s.cash;
 const tick=advance(s,NOW+1000);
 assert.ok(tick.infrastructureCashLoss>0);
 close(s.cash,initial+expectedCashChange);
 assert.equal(s.publicBudget,0);
 assert.ok(s.infrastructureCosts>0);
 const saved=exportState(s,NOW+1000);
 const restored=hydrateState(saved,NOW+11000);
 assert.ok(restored.infrastructureCashLoss>=s.infrastructureCashLoss);
 assert.ok(restored.infrastructureCosts>=s.infrastructureCosts);
 assert.ok(restored.cash<s.cash+10*finances.netToTreasuryPerSecond);
});
test('seriously neglected infrastructure can make overall cash balance decline',()=>{
 const s=growing();s.owned.matches=200;s.publicBudget=0;
 const before=s.cash;
 const finances=getBusinessEconomy(s);
 assert.ok(finances.infrastructure.costPerSecond>finances.taxesCollectedPerSecond+finances.businessIncomePerSecond);
 advance(s,NOW+1000);
 assert.ok(s.cash<before);
});
test('funding the required public levels removes the deficit without removing existing bonuses',()=>{
 const s=growing(),before=getBusinessEconomy(s).infrastructure;
 s.publicBudget=1e9;
 const caps=getPublicProgramCaps(s);
 for(const name of ['services','transport','housing'])assert.ok(caps[name]>=before.required[name]);
 for(let i=0;i<before.required.services;i++)assert.equal(spendPublicBudget(s,'services').ok,true);
 for(let i=0;i<before.required.transport;i++)assert.equal(spendPublicBudget(s,'transport').ok,true);
 for(let i=0;i<before.required.housing;i++)assert.equal(spendPublicBudget(s,'housing').ok,true);
 const after=getBusinessEconomy(s).infrastructure;
 assert.equal(after.costPerSecond,0);
 assert.deepEqual(after.missing,{services:0,transport:0,housing:0});
 const balance=s.cash,publicBefore=s.publicBudget;
 advance(s,NOW+1000);
 assert.ok(s.cash>balance);
 assert.ok(s.publicBudget>publicBefore);
});
test('public budget covers expenses first; no negative cash balance or unavoidable public shortage',()=>{
 const s=growing();
 const infra=getBusinessEconomy(s).infrastructure;
 s.publicBudget=infra.costPerSecond*2;
 const cash=s.cash;
 advance(s,NOW+1000);
 assert.equal(s.infrastructureCashLoss,0);
 assert.ok(s.cash>cash);
 assert.ok(s.publicBudget<infra.costPerSecond*2+getBusinessEconomy(s).taxesCollectedPerSecond);
 s.cash=0;s.publicBudget=0;
 advance(s,NOW+100000);
 assert.ok(s.cash>=0);
 assert.ok(s.publicBudget>=0);
});
